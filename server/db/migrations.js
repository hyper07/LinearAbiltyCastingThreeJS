/**
 * The schema, as migrations that run once each, in order (Database#migrate).
 * Never edit one that has shipped: add the next. Times are BIGINT milliseconds.
 *
 *   accounts    name, scrypt password hash, block state, plan (src/platform/plans.js)
 *   sessions    SHA-256 of each session token (never the token), expiry, address tag
 *   characters  a character per account per game (bag, stash, gear, gold, XP, spells) —
 *               AES-256-GCM encrypted and sealed to its account and game; a version per change
 *   items       every item that exists, once: who holds it, or that it lies on the
 *               floor of a run, or that it was sold or used up. `uid` is the primary
 *               key — an item cannot exist twice
 *   ledger      every change of gold, with the reason and the balance after
 *   events      the history: each row HMAC-chained to the row before. `data` stays
 *               TEXT: the chain hashes those exact characters
 *   strikes     rule breaks, with their weight; enough of them block the account
 *   ip_blocks   blocked addresses, as a keyed hash
 *   assets      the shared library: classes, skills, items, weapons, levels
 *   games       published games (the home page): title, author, card, spec, plays
 *   game_levels each published game's levels, in order (the rules load them by id)
 *   game_plays  play counts for the built-in games, which are files
 */
