/**
 * The schema, as migrations that run once each, in order (Database#migrate).
 * Never edit one that has shipped: add the next. Times are BIGINT milliseconds.
 *
 *   accounts    name, scrypt password hash, block state, plan (src/platform/plans.js)
 *   sessions    SHA-256 of each session token (never the token), expiry, address tag
 *   characters  the character (bag, stash, gear, gold, XP, spells) — AES-256-GCM
 *               encrypted and sealed to its account; a version per change
 *   items       every item that exists, once: who holds it, or that it lies on the
 *               floor of a run, or that it was sold or used up. `uid` is the primary
 *               key — an item cannot exist twice
 *   ledger      every change of gold, with the reason and the balance after
 *   events      the history: each row HMAC-chained to the row before. `data` stays
 *               TEXT: the chain hashes those exact characters
 *   strikes     rule breaks, with their weight; enough of them block the account
 *   ip_blocks   blocked addresses, as a keyed hash
 *   assets      the shared library: classes, skills, items, weapons, levels
 */
export const MIGRATIONS = [
  {
    id: '001-game',
    sql: `
      CREATE TABLE accounts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        name_key TEXT NOT NULL UNIQUE,
        pass_hash TEXT NOT NULL,
        created BIGINT NOT NULL,
        created_ip_tag TEXT,
        created_ip_enc TEXT,
        failed_logins INTEGER NOT NULL DEFAULT 0,
        locked_until BIGINT NOT NULL DEFAULT 0,
        blocked_until BIGINT NOT NULL DEFAULT 0,
        block_reason TEXT,
        blocks INTEGER NOT NULL DEFAULT 0,
        last_login BIGINT,
        plan TEXT NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'plus'))
      );
      CREATE INDEX accounts_created_ip ON accounts (created_ip_tag, created);
      CREATE TABLE sessions (
        token_hash TEXT PRIMARY KEY,
        account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
        created BIGINT NOT NULL,
        expires BIGINT NOT NULL,
        ip_tag TEXT,
        ip_enc TEXT,
        agent TEXT
      );
      CREATE INDEX sessions_account ON sessions (account_id, created);
      CREATE TABLE characters (
        account_id BIGINT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
        state TEXT NOT NULL,
        version INTEGER NOT NULL,
        updated BIGINT NOT NULL
      );
      CREATE TABLE items (
        uid TEXT PRIMARY KEY,
        owner BIGINT REFERENCES accounts(id),
        state TEXT NOT NULL CHECK (state IN ('held', 'floor', 'sold', 'used', 'destroyed')),
        run TEXT,
        source TEXT NOT NULL,
        data JSONB NOT NULL,
        created BIGINT NOT NULL,
        updated BIGINT NOT NULL
      );
      CREATE INDEX items_owner ON items (owner, state);
      CREATE INDEX items_run ON items (run, state);
      CREATE TABLE ledger (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        account_id BIGINT NOT NULL REFERENCES accounts(id),
        delta BIGINT NOT NULL,
        balance BIGINT NOT NULL,
        reason TEXT NOT NULL,
        ref TEXT,
        at BIGINT NOT NULL
      );
      CREATE INDEX ledger_account ON ledger (account_id, id);
      CREATE TABLE events (
        id BIGINT PRIMARY KEY,
        at BIGINT NOT NULL,
        account_id BIGINT,
        type TEXT NOT NULL,
        data TEXT NOT NULL,
        prev_hash TEXT NOT NULL,
        hash TEXT NOT NULL
      );
      CREATE INDEX events_account ON events (account_id, id);
      CREATE TABLE strikes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        account_id BIGINT NOT NULL REFERENCES accounts(id),
        rule TEXT NOT NULL,
        weight DOUBLE PRECISION NOT NULL,
        detail TEXT,
        at BIGINT NOT NULL
      );
      CREATE INDEX strikes_account ON strikes (account_id, at);
      CREATE TABLE ip_blocks (
        ip_tag TEXT PRIMARY KEY,
        until BIGINT NOT NULL,
        reason TEXT
      );
    `
  },
  {
    id: '002-library',
    sql: `
      CREATE TABLE assets (
        id TEXT PRIMARY KEY,
        kind TEXT NOT NULL,
        name TEXT NOT NULL,
        summary TEXT NOT NULL DEFAULT '',
        author TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL CHECK (status IN ('official', 'shared', 'draft', 'hidden')),
        featured BOOLEAN NOT NULL DEFAULT FALSE,
        data JSONB NOT NULL,
        fingerprint JSONB NOT NULL DEFAULT '{}',
        parent TEXT,
        uses INTEGER NOT NULL DEFAULT 0,
        created BIGINT NOT NULL,
        updated BIGINT NOT NULL
      );
      CREATE INDEX assets_kind ON assets (kind, status);
    `
  }
];
